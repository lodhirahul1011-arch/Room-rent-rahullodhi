/** Dependency-free *source contract* assertions; not an HTTP security test. */
const {readFileSync}=require('node:fs');const {join}=require('node:path');const assert=require('node:assert/strict');
const root=join(__dirname,'..');let count=0;
const source=(...parts)=>readFileSync(join(root,...parts),'utf8');
function expect(label,condition){assert.ok(condition,label);count++;}
const auth=source('apps/api/src/core/auth.js');
expect('sessions validated by DB',auth.includes('AuthSession.findOne'));
expect('active organization membership validated',auth.includes('Membership.findOne'));
expect('JWT algorithm and issuer checked',auth.includes("algorithms:['HS256']"));
const catalog=source('apps/api/src/modules/catalog/routes.js');
expect('catalog requires tenant authentication',catalog.includes("router.use(auth,roles('tenant'))"));
expect('catalog includes only explicitly open properties',catalog.includes('acceptingEnrollments:true'));
expect('catalog excludes occupied rooms',catalog.includes('!used.has'));
const enroll=source('apps/api/src/modules/enrollments/routes.js');
expect('enrollment must target accepting properties',enroll.includes('property.acceptingEnrollments'));
expect('enrollment approval uses DB transaction',enroll.includes('session.withTransaction'));
const finance=source('apps/api/src/modules/finance/routes.js');
expect('finance transaction wrapper exists',finance.includes('session.withTransaction'));
expect('payment requires submitted before verification',finance.includes("status:'submitted'"));
expect('tenant finance data filtered to own tenant',finance.includes("q.tenantId=req.actor.tenantId"));
expect('payments verified before ledger credit',finance.includes("sourceType:'payment'"));
const files=source('apps/api/src/modules/files/routes.js');
expect('private downloads require auth',files.includes('r.use(auth)'));
expect('private downloads enforce recipient permissions',files.includes('rules.recipientPermission'));
const invoice=source('apps/web/app/owner/invoices/print/[id]/page.tsx');
expect('live invoice print never displays local-only mock',invoice.includes('LIVE_MODE?<LiveInvoiceArchive'));
const api=source('apps/web/services/live/api.ts');
expect('live API sends authorization header',api.includes("headers.set('Authorization'"));
expect('live API refresh flow exists',api.includes('refreshAccess'));
console.log(`B8 security/source contracts: ${count}/${count} passed (static only).`);
